#!/usr/bin/env node
// ══════════════════════════════════════════════════════════
// Embed real glTF models as base64 into a plain JS module.
//
// Same reasoning as the font-embedding step in bundle-single-file.mjs:
// this project ships as a single self-contained file with zero
// external asset fetches, ever. Real GLB files are binary, so the
// only way in is base64-inlined as string data, decoded back to an
// ArrayBuffer at runtime by ModelLibrary.js.
//
// Scans three source directories, each becoming its own registry
// category (prefix keeps keys collision-free by construction, and
// lets ModelLibrary/integration code reason about "what kind of
// thing is this" without a separate lookup table):
//   assets-src/models/   -> "model:<name>"   rigged/animated characters
//   assets-src/items/    -> "item:<name>"    project-owner-provided props
//   assets-src/megakit/  -> "prop:<name>"    Quaternius Fantasy Props MegaKit
//
// Run manually (not part of the normal build) whenever a model is
// added/changed — output is checked in like any other source file,
// so `npm run dev`/`build`/`bundle` never need network access or
// this script.
// ══════════════════════════════════════════════════════════

import { readFileSync, writeFileSync, readdirSync } from 'fs';
import { fileURLToPath } from 'url';
import path from 'path';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT_FILE = path.join(__dirname, '..', 'src', 'data', 'generatedModels.js');

const SOURCES = [
  { dir: 'models', prefix: 'model' },
  { dir: 'items', prefix: 'item' },
  { dir: 'megakit', prefix: 'prop' },
  // The MegaKit ships ~94 props that all share four trim-sheet
  // material sets. Embedded one-file-per-prop, each file has to carry
  // its own copy of those sheets — 61 props came to 8.5 MB that way,
  // almost all of it the same textures over and over. Merged into a
  // single atlas (one Scene per prop, textures present once) the whole
  // 94 costs 3.7 MB. ModelLibrary expands this back out into the same
  // "prop:<Name>" keys at load time, so call sites don't know or care.
  { dir: 'atlas', prefix: 'atlas' },
];

let totalRaw = 0;
const entries = [];

for (const { dir, prefix } of SOURCES) {
  const srcDir = path.join(__dirname, '..', 'assets-src', dir);
  let files;
  try {
    files = readdirSync(srcDir).filter(f => f.endsWith('.glb'));
  } catch {
    continue; // directory doesn't exist yet — fine, just skip it
  }
  for (const f of files) {
    const buf = readFileSync(path.join(srcDir, f));
    totalRaw += buf.length;
    const name = path.basename(f, '.glb');
    const key = `${prefix}:${name}`;
    const constName = `MODEL_${prefix.toUpperCase()}_${name.toUpperCase().replace(/[^A-Z0-9]/g, '_')}`;
    entries.push({ key, constName, b64: buf.toString('base64'), rawBytes: buf.length });
  }
}

if (!entries.length) {
  console.error('No .glb files found in any assets-src/{models,items,megakit} directory.');
  process.exit(1);
}

const header =
`// ══════════════════════════════════════════════════════════
// AUTO-GENERATED by tools/embed-models.mjs — do not hand-edit.
// Base64 payloads for real glTF models. Provenance/license per
// category: assets-src/models/LICENSE.txt (KayKit, CC0),
// assets-src/items/LICENSE.txt (project-owner-provided),
// assets-src/megakit/LICENSE.txt (Quaternius Fantasy Props
// MegaKit, CC0).
// Regenerate with: node tools/embed-models.mjs
// ══════════════════════════════════════════════════════════

`;

const body = entries
  .map(e => `export const ${e.constName} = ${JSON.stringify(e.b64)};`)
  .join('\n\n');

const registry =
  `\n\nexport const MODEL_REGISTRY = {\n` +
  entries.map(e => `  ${JSON.stringify(e.key)}: ${e.constName},`).join('\n') +
  `\n};\n`;

writeFileSync(OUT_FILE, header + body + registry);

console.log(`Embedded ${entries.length} model(s):`);
for (const e of entries) {
  console.log(`  ${e.key}: ${(e.rawBytes / 1024 / 1024).toFixed(2)} MB raw -> ${(e.b64.length / 1024 / 1024).toFixed(2)} MB base64`);
}
console.log(`Total raw: ${(totalRaw / 1024 / 1024).toFixed(2)} MB`);
console.log(`Wrote ${path.relative(process.cwd(), OUT_FILE)}`);
